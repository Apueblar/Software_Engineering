m.addConstr(quicksum(L[i] * L_quantity[i] for i in range(len(L))) <= Lmax)

for i in range(len(L)):
  m.addConstr(L_quantity[i] >= 0) # Minimum of 0 for quantity

for i in range(len(L)):
  m.addConstr(L[i] * L_quantity[i] <= Lmax) # Max of Length for every length

m.optimize()

