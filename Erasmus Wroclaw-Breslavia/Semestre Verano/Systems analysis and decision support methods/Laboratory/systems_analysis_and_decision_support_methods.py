"""###Problem 3:
Given P={2,1.5,3,...} (Time for completing job i), N={10,45,50,...} (Min Releasing time of Job i).
The last job must finish the earlier.
"""

import random
from gurobipy import Model, GRB, quicksum

NumberJobs = 10

P = [random.randint(1, 100) for _ in range(NumberJobs)]

N = [0]
for i in range(1, NumberJobs):
    N.append(N[i-1] + random.randint(1, 100))

m = Model("Problem_3")

Cmax = m.addVar(lb=0, vtype=GRB.CONTINUOUS)
S = m.addVars(NumberJobs, lb=0, vtype=GRB.CONTINUOUS)
C = m.addVars(NumberJobs, lb=0, vtype=GRB.CONTINUOUS)

x = m.addVars(NumberJobs, NumberJobs, vtype=GRB.BINARY)

m.setObjective(Cmax, GRB.MINIMIZE)

M = sum(P) + max(N)

for j in range(NumberJobs):
    m.addConstr(C[j] == S[j] + P[j])
    m.addConstr(S[j] >= N[j])
    m.addConstr(Cmax >= C[j])

for i in range(NumberJobs):
    for j in range(NumberJobs):
        if i != j:
            m.addConstr(S[i] >= C[j] - M * (1 - x[i, j]))
            m.addConstr(S[j] >= C[i] - M * x[i, j])
            m.addConstr(x[i, j] + x[j, i] == 1)

m.optimize()

# Print results
if m.status == GRB.OPTIMAL:
    print("Cmax:", Cmax.x)
    for j in range(NumberJobs):
        print(f"Job {j}: Start={S[j].x}, Completion={C[j].x}, Release={N[j]}, Processing={P[j]}")

