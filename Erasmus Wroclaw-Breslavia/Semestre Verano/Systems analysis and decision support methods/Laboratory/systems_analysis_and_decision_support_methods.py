"""# Class 3

###Problem 1:
Given T={1,2,3,4,...} (Triangle IDs), D={1,2,3,...} (Dot IDs), C={3,4,7,...} where Ci = cost of Ti, d={{5,2,15},{5,7,8},{64,2,4},{7,5,9}} (Example 3 triangles, 4 dots) where dij = distance between Ti and Dj. And a cost bound (B >= sum(T selected))
"""

import random
from gurobipy import Model, GRB, quicksum

num_triangles = 10
num_dots = 10
B = 100

print(f"Number of Triangles = {num_triangles}")
print(f"Number of Dots = {num_dots}")
print(f"Bound = {B}")

C = [random.randint(1, 100) for _ in range(num_triangles)] # Cost of each triangle
d = [[random.randint(1, 100) for _ in range(num_dots)] for _ in range(num_triangles)] # Distance between each triangle and dot

for i in range(num_triangles):
    print(f"T{i+1:>2} | C: {C[i]:>3} | d: {d[i]}")
print()

m = Model(name='Problem 1')
y = m.addVars(num_triangles, vtype=GRB.BINARY) # Triangles selected
x = m.addVars(num_triangles, num_dots, vtype=GRB.BINARY) # If dot(j) is assigned to tri(i)

# C[i] / d[i,j] / y[i] / x[i,j]
m.setObjective(quicksum(quicksum(d[i][j] * x[i,j] for i in range(num_triangles)) for j in range(num_dots)))

m.addConstr(quicksum(y[i] * C[i] for i in range(num_triangles)) <= B)

for j in range(num_dots):
  m.addConstr(quicksum(x[i,j] for i in range(num_triangles)) == 1) # Each dot has at most/least 1 triangle

for i in range(num_triangles):
    for j in range(num_dots):
        m.addConstr(x[i,j] <= y[i])

m.optimize()

# Print results
if m.status == GRB.OPTIMAL:
    print("\nOptimal Solution Found!\n")

    print("Selected Triangles:")
    for i in range(num_triangles):
        if y[i].x > 0.5:
            print(f"Triangle {i} selected (Cost = {C[i]})")

    print("\nDot Assignments:")
    for j in range(num_dots):
        for i in range(num_triangles):
            if x[i, j].x > 0.5:
                print(f"Dot {j} -> Triangle {i} (Distance = {d[i][j]})")

    print(f"\nTotal Distance (Objective Value): {m.objVal}")
    print(f"\nThe total sum of the triangles cost is {sum(C[i] for i in range(num_triangles) if y[i].x > 0.5)} <= {B} = Bound")
else:
    print("No optimal solution found.")

"""###Problem 2:
Given W={1,2,3,4,...,N} (Workers), J={1,2,3,...,M} (Jobs), C={{5,2,15},{5,7,8},{64,2,4},{7,5,9}} where Cij = cost of job(j), maintained by worker(i). And a cost bound (B >= sum(Cost))

import random
from gurobipy import Model, GRB, quicksum
"""

num_workers = 10
num_jobs = 25
B = 100

print(f"Number of Workers = {num_workers}")
print(f"Number of Jobs = {num_jobs}")
print(f"Bound = {B}")

C = [[random.randint(1, 100) for _ in range(num_jobs)] for _ in range(num_workers)] # Cost between each job and each worker

# Header
print("     " + " ".join(f"job{j+1:>3}" for j in range(num_jobs)))
# Rows
for i, row in enumerate(C):
    print(f"w{i+1:<3} " + " ".join(f"{val:>6}" for val in row))

m = Model(name='Problem 2')

x = m.addVars(num_workers, num_jobs, vtype=GRB.BINARY) # If job(j) is assigned to worker(i)

m.setObjective(sum(sum(x[i,j] for i in range(num_workers)) for j in range(num_jobs)), GRB.MAXIMIZE)

m.addConstr(quicksum(quicksum(x[i,j] * C[i][j] for i in range(num_workers)) for j in range(num_jobs)) <= B)

for j in range(num_jobs):
  m.addConstr(quicksum(x[i,j] for i in range(num_workers)) <= 1) # Each job has at most 1 worker
for i in range(num_workers):
  m.addConstr(quicksum(x[i,j] for j in range(num_jobs)) <= 1) # Each worker has at most 1 job

m.optimize()

# Print solution
if m.status == GRB.OPTIMAL:
    print("\nOptimal assignment:\n")

    total_cost = 0
    total_jobs = 0

    for i in range(num_workers):
        for j in range(num_jobs):
            if x[i, j].X > 0.5:  # variable is 1
                print(f"Worker w{i+1:<2} -> Job job{j+1:<2}  (Cost = {C[i][j]:<3})")
                total_cost += C[i][j]
                total_jobs += 1

    print("\nSummary:")
    print(f"Total assigned jobs = {total_jobs}")
    print(f"Total cost = {total_cost} <= {B} = Bound")

"""# Class 4

###Problem 1:
Given Lmax=the length of a rope and L={2,1.5,3,...} (Lengths of subropes), N={10,45,13,...} (Money you earn per L of subropes). Maximize the Profit sum(N) given that sum(selected L) <= Lmax
"""

import random
from gurobipy import Model, GRB, quicksum

Lmax = 235 # Length of the rope
L = [random.randint(1, 100) for _ in range(10)] # Lengths of subropes
N = [random.randint(1, 100) for _ in range(len(L))] # Money you earn per L of subropes

print(f"Length of rope = {Lmax}")
for i in range(len(L)):
    print(f"L_sub: {L[i]:>3} | N: {N[i]:>3}")
print()

m = Model(name='Problem 1')
L_quantity = m.addVars(len(L), vtype=GRB.INTEGER) # Subropes selected

# Lmax, L[i], N[i], L_bin[i]
